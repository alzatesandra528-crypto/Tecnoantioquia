export function mergeSite(stored = {}) {
  return deepMerge(defaultSite, stored);
}

function deepMerge(base, extra) {
  if (Array.isArray(base)) {
    return Array.isArray(extra) && extra.length ? extra : base;
  }
  if (base && typeof base === "object") {
    const out = { ...base };
    for (const key of Object.keys(extra || {})) {
      out[key] = key in base ? deepMerge(base[key], extra[key]) : extra[key];
    }
    return out;
  }
  return extra === undefined || extra === null ? base : extra;
}
